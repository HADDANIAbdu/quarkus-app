CREATE TABLE dicom_instance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_identifier VARCHAR(64) NOT NULL,
    modality VARCHAR(16) NOT NULL,
    study_uid VARCHAR(64) NOT NULL,
    sop_instance_uid VARCHAR(64) NOT NULL UNIQUE
);

CREATE INDEX idx_dicom_instance_study
    ON dicom_instance(study_uid);